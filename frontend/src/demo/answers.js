const normalize = (s) => s.replace(/[\s?？.!,()（）]/g, '');

export function findDemoAnswer(text) {
  const t = normalize(text);
  for (const qa of DEMO_QA) {
    if (normalize(qa.question) === t) return qa.answer;
  }
  for (const qa of DEMO_QA) {
    if (qa.keywords.some(group => group.every(k => t.includes(normalize(k))))) return qa.answer;
  }
  return null;
}
